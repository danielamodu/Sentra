// FormatProposalBranchName creates a standard Git proposal branch name.
func FormatProposalBranchName(proposalID string) string {
	cleanID := strings.ToLower(strings.ReplaceAll(proposalID, " ", "-"))
	return fmt.Sprintf("ops/proposal-%s", cleanID)
}

// BundleProposalArtifacts bundles the machine-readable and human-readable artifacts for a proposal.
func BundleProposalArtifacts(
	prop *ops.Proposal,
	origCfg, propCfg sim.SystemConfig,
	verdict *verify.Verdict,
	adj *gov.AdjudicationResult,
) (*ProposalArtifacts, error) {
	if prop == nil {
		return nil, fmt.Errorf("proposal is nil")
	}

	propJSON, err := json.MarshalIndent(prop, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal proposal.json: %w", err)
	}

	diff := ops.ConfigDiff(origCfg, propCfg)

	var verifJSON []byte
	if verdict != nil {
		verifJSON, err = json.MarshalIndent(verdict, "", "  ")
		if err != nil {
			return nil, fmt.Errorf("marshal verification_report.json: %w", err)
		}
	}

	var mdBuilder strings.Builder
	mdBuilder.WriteString(fmt.Sprintf("# Evidence & Verification Summary: %s\n\n", prop.ID))
	mdBuilder.WriteString(fmt.Sprintf("- **Hypothesis:** %s\n", prop.Hypothesis.Description))
	mdBuilder.WriteString(fmt.Sprintf("- **Target Config Version:** %s\n", prop.TargetConfigVersion))
	mdBuilder.WriteString(fmt.Sprintf("- **Author:** %s\n", prop.AuthorID))

	if verdict != nil {
		mdBuilder.WriteString(fmt.Sprintf("- **Verifier Status:** `%s`\n", verdict.Status))
		mdBuilder.WriteString(fmt.Sprintf("- **Total Findings:** %d\n", len(verdict.Findings)))
		mdBuilder.WriteString(fmt.Sprintf("- **Total Properties Evaluated:** %d\n", len(verdict.Properties)))
	}
	if adj != nil {
		mdBuilder.WriteString(fmt.Sprintf("- **Governance Eligibility:** %t\n", adj.Eligible))
		if len(adj.RejectionReasons) > 0 {
			mdBuilder.WriteString("\n### Rejection Reasons\n")
			for _, r := range adj.RejectionReasons {
				mdBuilder.WriteString(fmt.Sprintf("- ❌ %s\n", r))
			}
		}
	}

	return &ProposalArtifacts{
		ProposalJSON:           propJSON,
		ConfigDiff:             diff,
		VerificationReportJSON: verifJSON,
		EvidenceSummaryMD:      mdBuilder.String(),
	}, nil
}

// GenerateMergeRequestDescription generates a rich, transparent GitLab Merge Request description.
func GenerateMergeRequestDescription(
	prop *ops.Proposal,
	origCfg, propCfg sim.SystemConfig,
	baseSum, candSum *sim.ExperimentSummary,
	verdict *verify.Verdict,
	adj *gov.AdjudicationResult,
	evidenceDigest string,
) string {
	var b strings.Builder

	b.WriteString(fmt.Sprintf("# Operational Proposal: %s\n\n", prop.ID))
	b.WriteString("> **Notice:** This is an autonomous operational change proposal generated by Sentra. It is subject to independent verification and requires human authorization before promotion.\n\n")

	// 1. Problem Statement & Observed Symptoms
	b.WriteString("## 1. Operational Problem Statement\n")
	b.WriteString(fmt.Sprintf("**Observed Symptom:** `%s`\n\n", prop.Hypothesis.Symptom))
	b.WriteString("### Supporting Telemetry Observations\n")
	b.WriteString("| Metric | Observed Value | Unit | Context | Evidence Ref |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, o := range prop.Observations {
		b.WriteString(fmt.Sprintf("| `%s` | `%.2f` | %s | %s | `%s` |\n",
			o.Metric, o.Value, o.Unit, o.Context, o.EvidenceRef))
	}
	b.WriteString("\n")

	// 2. Agent Hypothesis & Rationale
	b.WriteString("## 2. Agent Hypothesis & Operational Rationale\n")
	b.WriteString(fmt.Sprintf("**Hypothesis ID:** `%s`\n\n", prop.Hypothesis.ID))
	b.WriteString(fmt.Sprintf("**Mechanism:** %s\n\n", prop.Hypothesis.Description))
	b.WriteString(fmt.Sprintf("**Rationale:** %s\n\n", prop.Hypothesis.Rationale))

	// 3. Proposed Configuration Changes & Diff
	b.WriteString("## 3. Proposed Configuration Changes\n")
	b.WriteString("```diff\n")
	b.WriteString(ops.ConfigDiff(origCfg, propCfg))
	b.WriteString("\n```\n\n")

	// 4. Baseline vs Candidate Telemetry Comparison
	if baseSum != nil && candSum != nil {
		b.WriteString("## 4. Telemetry Impact Comparison (Simulation)\n")
		b.WriteString("| Operational Metric | Baseline | Candidate Proposal | Delta |\n")
		b.WriteString("|---|---|---|---|\n")
		b.WriteString(fmt.Sprintf("| **Goodput (Completed)** | %d req | %d req | %+d req |\n",
			baseSum.Completed, candSum.Completed, candSum.Completed-baseSum.Completed))
		b.WriteString(fmt.Sprintf("| **Failed Requests** | %d req | %d req | %+d req |\n",
			baseSum.Failed, candSum.Failed, candSum.Failed-baseSum.Failed))
		b.WriteString(fmt.Sprintf("| **Shed Requests** | %d req | %d req | %+d req |\n",
			baseSum.Shed, candSum.Shed, candSum.Shed-baseSum.Shed))
		b.WriteString(fmt.Sprintf("| **Wasted Work Ratio** | %.1f%% | %.1f%% | %+.1f%% |\n",
			baseSum.WastedShare*100, candSum.WastedShare*100, (candSum.WastedShare-baseSum.WastedShare)*100))
		b.WriteString(fmt.Sprintf("| **Retry Amplification** | %.2fx | %.2fx | %+.2fx |\n",
			baseSum.Amplification, candSum.Amplification, candSum.Amplification-baseSum.Amplification))
		b.WriteString(fmt.Sprintf("| **Work After Expiry** | %d att | %d att | %+d att |\n",
			baseSum.WorkAfterExpiry, candSum.WorkAfterExpiry, candSum.WorkAfterExpiry-baseSum.WorkAfterExpiry))
		b.WriteString("\n")
	}

	// 5. Independent Verifier Adjudication
	b.WriteString("## 5. Independent Verifier Adjudication\n")
	if verdict != nil {
		b.WriteString(fmt.Sprintf("- **Verdict Status:** `%s`\n", verdict.Status))
		b.WriteString(fmt.Sprintf("- **Total Findings:** %d\n", len(verdict.Findings)))
		b.WriteString(fmt.Sprintf("- **Evidence Digest:** `%s`\n", evidenceDigest))

		if len(verdict.Findings) > 0 {
			b.WriteString("\n### Verifier Findings / Counterexamples\n")
			for _, f := range verdict.Findings {
				b.WriteString(fmt.Sprintf("- ⚠️ `[%s]` %s (seq: %d)\n", f.Code, f.Message, f.EffectSeq))
			}
		}
	} else {
		b.WriteString("_Pending independent verifier pipeline execution._\n")
	}
	b.WriteString("\n")

	// 6. Governance Compliance & Remaining Uncertainty
	b.WriteString("## 6. Governance Compliance & Risk Assessment\n")
	if adj != nil {
		b.WriteString(fmt.Sprintf("- **Promotion Eligibility:** `%t`\n", adj.Eligible))
		b.WriteString(fmt.Sprintf("- **Safety Properties Passed:** %d\n", len(adj.PassedSafetyProperties)))
		if len(adj.FailedSafetyProperties) > 0 {
			b.WriteString(fmt.Sprintf("- **Safety Properties Failed:** %d\n", len(adj.FailedSafetyProperties)))
		}
	}
	b.WriteString("\n### Potential Regressions & Operational Risks\n")
	for _, reg := range prop.PotentialRegressions {
		b.WriteString(fmt.Sprintf("- ⚠️ %s\n", reg))
	}
	b.WriteString("\n")

	// 7. Human Authorization Boundary
	b.WriteString("## 7. Required Human Authorization\n")
	b.WriteString("- [ ] **Required Role:** `infrastructure-lead`\n")
	b.WriteString("- [ ] **Self-Approval Check:** Agent `agent-sentra` is forbidden from self-authorizing this change.\n")
	b.WriteString("- [ ] **Promotion Gate:** Promotion to active runtime is blocked until explicit cryptographically signed human approval is recorded.\n")

	return b.String()
}

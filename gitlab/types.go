package gitlab

import (
	"time"

	"sentra/gov"
	"sentra/sim"
	"sentra/verify"
)

// MergeRequestPayload represents the data required to submit a GitLab Merge Request.
type MergeRequestPayload struct {
	Title        string   `json:"title"`
	SourceBranch string   `json:"source_branch"`
	TargetBranch string   `json:"target_branch"`
	Description  string   `json:"description"`
	Labels       []string `json:"labels"`
	ProposalID   string   `json:"proposal_id"`
	ConfigDigest string   `json:"config_digest"`
}

// ProposalArtifacts bundles the committed artifacts associated with an operational proposal.
type ProposalArtifacts struct {
	ProposalJSON           []byte `json:"proposal_json"`            // proposal.json
	ConfigDiff             string `json:"config_diff"`              // config.diff
	VerificationReportJSON []byte `json:"verification_report_json"` // verification_report.json
	EvidenceSummaryMD      string `json:"evidence_summary_md"`      // evidence_summary.md
}

// CIStageResult records the result of one GitLab CI pipeline stage.
type CIStageResult struct {
	Name      string        `json:"name"`
	Passed    bool          `json:"passed"`
	Duration  time.Duration `json:"duration"`
	Message   string        `json:"message"`
	ErrorText string        `json:"error_text,omitempty"`
}

// CIAdjudicationReport captures the machine-readable evaluation generated by the CI pipeline.
type CIAdjudicationReport struct {
	PipelineID          string                  `json:"pipeline_id"`
	Passed              bool                    `json:"passed"`
	Stages              []CIStageResult         `json:"stages"`
	VerificationVerdict *verify.Verdict         `json:"verification_verdict,omitempty"`
	AdjudicationResult  *gov.AdjudicationResult `json:"adjudication_result,omitempty"`
	BlockReason         string                  `json:"block_reason,omitempty"`
	PublishedAt         time.Time               `json:"published_at"`
}

// PromotionReport records the execution and validation of an authorized promotion.
type PromotionReport struct {
	PromotionID           string           `json:"promotion_id"`
	ProposalID            string           `json:"proposal_id"`
	PromotedAt            time.Time        `json:"promoted_at"`
	PromotedBy            string           `json:"promoted_by"`
	AppliedConfig         sim.SystemConfig `json:"-"`
	PostValidationVerdict *verify.Verdict  `json:"post_validation_verdict,omitempty"`
	Status                string           `json:"status"` // "SUCCESS", "REJECTED", "FAILED"
	RejectionReason       string           `json:"rejection_reason,omitempty"`
	AuditTrailHash        string           `json:"audit_trail_hash"`
}
